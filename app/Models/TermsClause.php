#[Fillable(['position', 'title', 'body'])]
#[WithoutTimestamps]
class TermsClause extends Model
{
    use HasFactory;

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'position' => 'integer',
        ];
    }
}
